// Builds backend/reel-engine/src/iconData.ts from lucide-react's icon files, so the reel engine can draw any of
// ~1,500 icons as an extruded 3D tile without importing React components. Run: node scripts/gen-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = 'node_modules/lucide-react/dist/esm/icons';
const out = {};
for (const f of readdirSync(dir)) {
  if (!f.endsWith('.js')) continue;
  const src = readFileSync(`${dir}/${f}`, 'utf8');
  const m = src.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\);\s*\nexport/);
  if (!m) continue; // an alias of another icon
  let nodes;
  try {
    nodes = new Function(`return ${m[1]}`)();
  } catch {
    continue;
  }
  const shapes = nodes
    .filter(([tag]) => ['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse'].includes(tag))
    .map(([tag, attrs]) => {
      const { key, ...rest } = attrs;
      return [tag, rest];
    });
  if (shapes.length) out[f.replace(/\.js$/, '')] = shapes;
}
const names = Object.keys(out).sort();
const sorted = Object.fromEntries(names.map((n) => [n, out[n]]));
writeFileSync(
  'backend/reel-engine/src/iconData.ts',
  `// Generated by scripts/gen-icons.mjs from lucide-react (ISC licence). Do not edit by hand.\nexport type IconShape = [string, Record<string, string | number>];\nexport const ICONS: Record<string, IconShape[]> = ${JSON.stringify(sorted)};\n`,
);
console.log(names.length, 'icons');
